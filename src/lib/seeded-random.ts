// Deterministic PRNG seeded from an arbitrary string — used only for the
// guest dashboard's "same picks on reload, different picks on refresh"
// behavior (see select-daily.ts's getGuestDailySelection). Not
// cryptographic; never use this for anything security-sensitive.
export function seededRng(seed: string): () => number {
  let h = 0;
  for (let i = 0; i < seed.length; i++) {
    h = (Math.imul(h, 31) + seed.charCodeAt(i)) | 0;
  }
  // mulberry32
  return function next() {
    h |= 0;
    h = (h + 0x6d2b79f5) | 0;
    let t = Math.imul(h ^ (h >>> 15), 1 | h);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
